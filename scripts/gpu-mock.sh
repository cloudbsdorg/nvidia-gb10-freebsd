# gpu-mock.sh - build the GPU mock: the CUSE daemon, the seam and the RM
# engine.  The logic lives here in sh(1); the Makefile only names the
# targets, so both GNU make and bmake drive it.
#
# usage: gpu-mock.sh build | clean | flags
#
# The NVIDIA headers are the open-gpu-kernel-modules of the tag in SOURCES.
# They are the MIT headers of NVIDIA's own RM: the mock speaks that ABI and
# needs no other source.
set -u

here=$(dirname "$0")
root=$(cd "$here/.." && pwd)
src=$root/src/gb10-gpu-mock
obj=$src/build
work=${GB10_WORK:-$root/work}

. "$here/lib.sh"

tag=$(sources_get "$root/SOURCES" ogkm_tag)
if [ -z "$tag" ]; then
	echo "gpu-mock.sh: $root/SOURCES has no ogkm_tag line" >&2
	exit 1
fi
ogkm=$work/sources/open-gpu-kernel-modules-$tag
if [ ! -d "$ogkm/src/common/sdk/nvidia/inc" ]; then
	echo "gpu-mock.sh: the NVIDIA headers are not at $ogkm" >&2
	echo "gpu-mock.sh: run scripts/fetch-sources.sh, or set GB10_WORK to" >&2
	echo "gpu-mock.sh: the work root that holds them" >&2
	exit 1
fi

inc="-I$src -I$ogkm/src/common/sdk/nvidia/inc"
inc="$inc -I$ogkm/src/common/sdk/nvidia/inc/ctrl"
inc="$inc -I$ogkm/src/nvidia/arch/nvalloc/unix/include"
inc="$inc -I$ogkm/src/common/inc"

cflags="-std=gnu11 -O2 -g -Wall -Wextra -Wno-unused-parameter -Werror"
cflags="$cflags -fPIC $inc"
ldflags="-lcuse"

srcdir=$src
objs="gpu_daemon.o gpu_json.o gpu_mock.o gpu_model.o gpu_rm.o gpu_seam.o"
# The seam shim: the same model, for a program that reads the hardware
# through the system calls.  It is a shared library: a preload.
shimobjs="gpu_json.o gpu_model.o gpu_rm.o gpu_seam.o gpu_shim.o"

case "${1:-}" in
flags)
	printf '%s\n' "$cflags"
	printf '%s\n' "$ldflags"
	exit 0
	;;
clean)
	rm -rf "$obj"
	exit 0
	;;
build) ;;
*)
	echo "usage: gpu-mock.sh build | clean | flags" >&2
	exit 2
	;;
esac

mkdir -p "$obj" || exit 1

# The model files of this checkout: the tool finds them when it is run from
# the tree, so a model is a name and not a path.  The name of the directory
# is in a generated header because a path may hold a space.
cat >"$obj/modeldir.h.new" <<EOF
/* Generated by scripts/gpu-mock.sh: the model files of this checkout. */
#define GB10_GPU_MOCK_SOURCE_MODELS "$root/data/models"
EOF
if ! cmp -s "$obj/modeldir.h.new" "$obj/modeldir.h" 2>/dev/null; then
	# The directory of the models changed: everything is built again.
	rm -f "$obj"/*.o "$obj/gpu-mock" "$obj/libgpubmockshim.so"
	mv -f "$obj/modeldir.h.new" "$obj/modeldir.h"
else
	rm -f "$obj/modeldir.h.new"
fi
cflags="$cflags -I$obj"

# One object per source: recompile only what changed.
for o in $objs $shimobjs; do
	c=${o%.o}.c
	if [ -f "$obj/$o" ] && [ "$obj/$o" -nt "$src/$c" ]; then
		continue
	fi
	# shellcheck disable=SC2086
	if ! cc $cflags -c "$src/$c" -o "$obj/$o" 2>"$obj/$c.log"; then
		echo "gpu-mock.sh: $c does not compile:" >&2
		cat "$obj/$c.log" >&2
		exit 1
	fi
done

if ! cc -o "$obj/gpu-mock" $(for o in $objs; do printf '%s ' "$obj/$o"; done) \
    $ldflags 2>"$obj/link.log"; then
	echo "gpu-mock.sh: the link failed:" >&2
	cat "$obj/link.log" >&2
	exit 1
fi
# The seam shim: a shared library, loaded with LD_PRELOAD.
if ! cc -shared -o "$obj/libgpubmockshim.so" \
    $(for o in $shimobjs; do printf '%s ' "$obj/$o"; done) \
    2>"$obj/link-shim.log"; then
	echo "gpu-mock.sh: the seam shim did not link:" >&2
	cat "$obj/link-shim.log" >&2
	exit 1
fi
printf 'gpu-mock: %s\n' "$obj/gpu-mock"
printf 'gpu-mock shim: %s\n' "$obj/libgpubmockshim.so"
exit 0
